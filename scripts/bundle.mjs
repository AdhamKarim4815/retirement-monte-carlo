// Concatenates src/*.js into dist/rmc.bundle.js, a plain classic script.
// Why: browsers refuse ES module imports on file:// URLs, so index.html loads this one file and the
// page works when double-clicked as well as on GitHub Pages. No minifying, no transpiling.
// Usage: node scripts/bundle.mjs [--check]   (--check exits 1 when dist/ is stale)

import { readFileSync, writeFileSync, mkdirSync, existsSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath, pathToFileURL } from 'node:url';

const root = join(dirname(fileURLToPath(import.meta.url)), '..');
const ORDER = ['stats', 'sim', 'presets', 'state', 'charts', 'app'];
const OUT = join(root, 'dist', 'rmc.bundle.js');

export function buildBundle() {
  const seen = new Map();
  const chunks = ORDER.map((name) => {
    const code = readFileSync(join(root, 'src', `${name}.js`), 'utf8')
      .split('\n')
      .filter((line) => !/^import\s.*\sfrom\s+'[^']+';?\s*$/.test(line))
      .map((line) => line.replace(/^export\s+(?=(const|let|function|async|class)\b)/, ''))
      .join('\n');
    if (/^\s*(import|export)\s/m.test(code)) throw new Error(`${name}.js uses import/export syntax the bundler does not handle`);
    for (const m of code.matchAll(/^(?:async\s+)?(?:const|let|function|class)\s+(\w+)/gm)) {
      if (seen.has(m[1])) throw new Error(`Top-level name "${m[1]}" is declared in both ${seen.get(m[1])}.js and ${name}.js`);
      seen.set(m[1], name);
    }
    return `// ---- src/${name}.js ----\n${code.trim()}\n`;
  });
  return `// Generated by scripts/bundle.mjs from src/*.js. Do not edit by hand.\n(function () {\n'use strict';\n${chunks.join('\n')}})();\n`;
}

if (process.argv[1] && import.meta.url === pathToFileURL(process.argv[1]).href) {
  const out = buildBundle();
  if (process.argv.includes('--check')) {
    const current = existsSync(OUT) ? readFileSync(OUT, 'utf8') : '';
    if (current !== out) {
      console.error('dist/rmc.bundle.js is out of date. Run: node scripts/bundle.mjs');
      process.exit(1);
    }
    console.log('dist/rmc.bundle.js is up to date.');
  } else {
    mkdirSync(dirname(OUT), { recursive: true });
    writeFileSync(OUT, out);
    console.log(`Wrote dist/rmc.bundle.js (${out.split('\n').length} lines).`);
  }
}
